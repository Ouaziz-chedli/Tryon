#!/usr/bin/env python3
"""One-command Colab job launcher (Team TRYON) — v2.

v2 fix: the --run string is executed via `bash -c` on the VM so that shell
chains (`&&`) actually chain. v1 passed the tokens as argv to python and
`&&`-chains silently ran only the first command.

Usage:
  python3 scripts/colab_launch.py --session track3_x --gpu A100 --fallback-gpu L4 \
      --tarball /tmp/harness_v5.tar.gz --work /content/work_x \
      --run "python3 -u tests/t.py && python3 -u run.py --round 5" [--timeout 3600]

Run it via a background bash (async) so the block returns as a notify.
Never include .pt/.npz in the tarball (Colab upload limit; data comes from HF).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import time

COLAB = "/home/chedli/.local/bin/colab"

LAUNCHER_TEMPLATE = '''"""Auto-generated by colab_launch.py v2."""
import os
import select
import subprocess
import sys
import tarfile

WORK = "{work}"
os.makedirs(WORK, exist_ok=True)
with tarfile.open("/content/{tarname}") as tar:
    tar.extractall(WORK)
os.chdir(WORK)

subprocess.run(
    [sys.executable, "-m", "pip", "install", "-q", "timm==1.0.31", "huggingface_hub"],
    check=True,
)

from huggingface_hub import hf_hub_download  # noqa: E402

for fname in ("model.pt", "forget_images.npz"):
    if not os.path.exists(os.path.join(WORK, fname)):
        hf_hub_download(
            repo_id="SprintML/unlearning", repo_type="dataset",
            filename=fname, local_dir=WORK,
        )
        print(f"downloaded {{fname}}", flush=True)

env = {{**os.environ, "PYTHONPATH": WORK}}
proc = subprocess.Popen(
    ["bash", "-c", {run_string}],
    env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1,
)
while True:
    ready, _, _ = select.select([proc.stdout], [], [], 15.0)
    if ready:
        line = proc.stdout.readline()
        if not line:
            if proc.poll() is not None:
                break
            continue
        print(line, end="", flush=True)
    else:
        print(".", end="", flush=True)
        if proc.poll() is not None:
            break
if proc.wait() != 0:
    raise SystemExit(proc.returncode)
print("COLAB_LAUNCH_DONE", flush=True)
'''


def run_colab(*args: str, timeout: int = 240) -> str:
    out = subprocess.run([COLAB, *args], capture_output=True, text=True, timeout=timeout)
    return out.stdout + out.stderr


def create_session(session: str, gpu: str, fallback: str, tries: int = 2) -> str:
    for attempt in range(tries):
        out = run_colab("new", "-s", session, "--gpu", gpu, timeout=240)
        if "READY" in out:
            return gpu
        print(f"[colab_launch] {gpu} refused (attempt {attempt + 1}): {out.strip()[-120:]}", flush=True)
        if fallback and gpu != fallback:
            gpu = fallback
        time.sleep(5)
    raise SystemExit(f"session creation failed for {session}")


def main() -> int:
    parser = argparse.ArgumentParser(description="One-command Colab job launcher (v2, bash -c chains).")
    parser.add_argument("--session", required=True)
    parser.add_argument("--gpu", default="A100")
    parser.add_argument("--fallback-gpu", default="L4")
    parser.add_argument("--tarball", required=True)
    parser.add_argument("--work", required=True)
    parser.add_argument("--run", required=True, help="Shell command line run inside the workdir (&& chains OK).")
    parser.add_argument("--timeout", type=int, default=3600)
    args = parser.parse_args()

    create_session(args.session, args.gpu, args.fallback_gpu)

    out = run_colab("upload", "-s", args.session, args.tarball,
                    f"/content/{pathlib.Path(args.tarball).name}", timeout=300)
    if "Uploaded" not in out:
        raise SystemExit(f"upload failed: {out[-200:]}")
    print(f"[colab_launch] uploaded {pathlib.Path(args.tarball).name}", flush=True)

    launcher = LAUNCHER_TEMPLATE.format(
        work=args.work, tarname=pathlib.Path(args.tarball).name,
        run_string=json.dumps(args.run),
    )
    local = f"/tmp/launch_{args.session}.py"
    pathlib.Path(local).write_text(launcher, encoding="utf-8")
    run_colab("upload", "-s", args.session, local, f"/content/launch_{args.session}.py", timeout=120)

    proc = subprocess.run(
        [COLAB, "exec", "-s", args.session, "--timeout", str(args.timeout), "-f", local],
        timeout=args.timeout + 120,
    )
    print(f"[colab_launch] exec rc={proc.returncode} — STOP the session when results are collected:", flush=True)
    print(f"[colab_launch]   {COLAB} stop -s {args.session}", flush=True)
    return proc.returncode


if __name__ == "__main__":
    raise SystemExit(main())
